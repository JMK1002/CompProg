#include <bits/stdc++.h>
using namespace std;

int n;

void encode() {
	cin >> n;
	for (int i = 0; i < n; i++) {
		string s;
		cin >> s;
		if (s == "000000000000") {
			for (int j = 0; j < 333; j++) cout << 9;
			cout << endl;
			continue;
		}

		for (int j = 0; j < 8; j++) {
			int dig = s[j] - '0';
			for (int m = 0; m < dig; m++) cout << j;
		}
		int a = (s[8] - '0') * 10 + (s[9] - '0');
		for (int j = 0; j < a; j++) cout << 8;
		a = (s[10] - '0') * 10 + (s[11] - '0');
		for (int j = 0; j < a; j++) cout << 9;
		cout << endl;
	}
}

void decode() {
	cin >> n;
	for (int i = 0; i < n; i++) {
		string s;
		cin >> s;
		vector<int> cnt(10, 0);
		for (char c : s) cnt[c - '0']++;
		if (cnt[9] == 333) {
			cout << "000000000000" << endl;
			continue;
		}
		string ans;
		for (int j = 0; j < 10; j++) {
			if ((j == 8 || j == 9) && cnt[j] < 10) {
				ans += "0";
			}
			ans += to_string(cnt[j]);
		}
		cout << ans << endl;
	}
}

void solve() {
	string s;
	cin >> s;
	if (s == "encode") encode();
	else decode();
}

int main() {
	istream::sync_with_stdio(0);
	cin.tie(nullptr);
	int t=1;
	// cin >> t;
	while (t--) {
		solve();
	}
	return 0;
}
